/**
 * toggleFaqId — تنها منطقِ باز/بسته شدن، به‌صورت خالص.
 *
 * چرا pure و نه state مستقیم؟ چون این پروژه تست DOM ندارد؛ اگر منطق اینجا
 * نبود، فقط با «رندر می‌شود» قابل اطمینان بود. با این شکل، رفتارِ واقعی
 * (باز بودن هم‌زمان چند آیتم، و بسته شدن دوبارهٔ همان آیتم) تست می‌شود.
 *
 * قرارداد: کلیک روی آیتم باز، آن را می‌بندد؛ کلیک روی آیتم بسته، بازش می‌کند.
 * چند آیتم می‌توانند هم‌زمان باز باشند — این تصمیمِ محصول است، نه پیش‌فرضِ
 * کتابخانه‌ای، و در صفحهٔ متعدد هم طبیعی‌تر است.
 */
export function toggleFaqId(open: readonly string[], id: string): string[] {
    return open.includes(id) ? open.filter((current) => current !== id) : [...open, id]
}

/** باز کردن همه / بستن همه — برای دکمهٔ کمکی بالای فهرست. */
export function setAllFaq(items: readonly FaqItem[], open: boolean): string[] {
    return open ? items.map((item) => item.id) : []
}

/** نمایهٔ سؤال‌ها برای پیدا کردن سریع با `?q=` یا جست‌وجوی سمت کلاینت. */
export function findFaq(id: string): FaqItem | undefined {
    return FAQ_ITEMS.find((item) => item.id === id)
}
