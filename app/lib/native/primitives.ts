/*
 * primitiveهای مشترک wrapperهای یادآور نیتیو
 * ---------------------------------------------------------
 * دو چیز اینجا زندگی می‌کنند که **هر دو** wrapper یادآور روزانه و یادآور تسک
 * به آن‌ها نیاز دارند و نباید در دو فایل جداگانه کپی شوند:
 *
 *  ۱. صف سریال عملیات نیتیو — تا `schedule` و `cancel` مربوط به یک شناسه هرگز
 *     درهم نیفتند. همه‌ی wrapperها از **یک صف** استفاده می‌کنند، پس حتی عملیات
 *     دو یادآور مختلف هم به ترتیب از پل عبور می‌کنند.
 *
 *  ۲. سیاست شناسه‌ی اعلان — یک نگاشت قطعی «کلید متنی ← عدد ۳۲ بیتی معتبر».
 *     یکتا بودن و محدوده‌ی مجاز اندروید اینجا یک‌بار تعریف و یک‌بار تست
 *     می‌شود، نه در هر wrapper.
 *
 * این ماژول هیچ state، هیچ UI و هیچ دسترسی مستقیمی به `window`/Capacitor ندارد
 * (صف در scope ماژول است و هرگز در SSR اجرا نمی‌شود چون فقط از چرخه‌ی عمر
 * کلاینت صدا زده می‌شود).
 */

/** سقف شناسه — زیر `2^31-1` (بیشینه‌ی int32 علامت‌دار اندروید) می‌مانیم. */
export const MAX_NOTIFICATION_ID = 2_000_000_000

/**
 * هش صحیحِ قطعی (djb2 روی ۳۲ بیت) — pure و بدون وابستگی.
 * برای ما فقط یک نگاشت یک‌به‌یکِ «کلید متنی ← عدد» لازم است، نه یک هش
 * رمزنگاری؛ پس استفاده از الگوریتم استاندارد کتابخانه‌ای لازم نیست.
 */
function stableIntHash(value: string): number {
    let hash = 5381

    for (let index = 0; index < value.length; index += 1) {
        // hash * 33 + code، در محدوده‌ی int32
        hash = (((hash << 5) + hash + value.charCodeAt(index)) | 0)
    }

    return hash >>> 0
}

/**
 * شناسه‌ی قطعی و پایدار اعلان برای یک کلید متنی.
 *
 * چرا به `dayKey` وابسته نباشد: هر یادآور در هر لحظه حداکثر یک اعلان فعال
 * دارد. با یک شناسه‌ی ثابت برای هر دامنه:
 *  - زمان‌بندی دوباره، اعلان قبلی را **جایگزین** می‌کند (id در اندروید کلید یکتا
 *    است) ⇒ هیچ‌وقت اعلان تکراری ساخته نمی‌شود؛
 *  - لغو کردنی نیازی به «به‌خاطر سپردنِ» زمان قبلی ندارد — همان تابع دوباره
 *    حساب می‌شود؛
 *  - بعد از ری‌استارت اپ یا تغییر زمان، همان id قابل بازیابی است.
 *
 * نتیجه در بازه‌ی `1 … MAX_NOTIFICATION_ID` است (نه صفر، چون صفر رزرو نشده).
 */
export function stableNotificationId(key: string): number {
    return 1 + (stableIntHash(key) % MAX_NOTIFICATION_ID)
}

/*
 * ترتیب فراخوانی‌های نیتیو
 * ------------------------
 * `schedule` و `cancel` هر دو از پل نیتیو عبور می‌کنند و ترتیبِ رسیدنشان به
 * سیستم‌عامل تضمین‌شده نیست. در چرخه‌ی عمر React، cleanup یک effect **قبل** از
 * اجرای effect بعدی اجرا می‌شود؛ پس بدون صف، ممکن است `cancel` بعد از `schedule`
 * بنشیند و اعلان تازه‌ساخته را لغو کند.
 *
 * این صف فقط در کلاینت وجود دارد و هیچ state ای ندارد؛ کارش فقط سریال‌کردن
 * عملیات نیتیو است.
 */
let nativeQueue: Promise<unknown> = Promise.resolve()

export function enqueueNative<T>(task: () => Promise<T>): Promise<T> {
    // اگر کار قبلی رد شده بود، این یکی هم باید اجرا شود (`onRejected` همان task است).
    const result = nativeQueue.then(task, task)

    nativeQueue = result.then(
        () => undefined,
        () => undefined,
    )

    return result
}
