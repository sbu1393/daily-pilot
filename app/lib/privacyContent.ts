/** بخش را با شناسه‌اش پیدا می‌کند؛ اگر نبود `undefined` می‌دهد. */
export function findPrivacySection(id: string): PrivacySection | undefined {
    return PRIVACY_SECTIONS.find((section) => section.id === id)
}

/** همه‌ی متن‌های یک بخش را در یک رشته‌ی واحد می‌دهد (برای جستجو و تست). */
export function flattenSection(section: PrivacySection): string {
    return section.blocks
        .map((block) => (block.kind === "p" ? block.text : block.items.join(" ")))
        .join("\n")
}

/** کل متن سیاست، برای جستجوی یک عبارت در کل صفحه. */
export function privacyFullText(): string {
    return PRIVACY_SECTIONS.map(flattenSection).join("\n")
}
