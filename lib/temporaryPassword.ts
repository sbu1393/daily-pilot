import { randomInt } from "crypto"

/**
 * تولید رمز عبور موقت — رمز موقت «رمز عبور» است، پس باید همان قدرت آماریِ رمز
 * عبور خوب را داشته باشد، نه صرفاً یک کد کوتاه قابل حدس.
 *
 * چرا فقط الفبا-عددی (بدون نویسهٔ سمبول)؟
 * این رشته را کاربر **از داخل ایمیل با چشم می‌خواند و با دست تایپ می‌کند**.
 * نویسه‌هایی مثل `! @ # $ % ^ & * ?`:
 *   • روی موبایل به کلید Shift نیاز دارند (خطای تایپ بالا)،
 *   • در بعضی کیبوردهای فارسی/لاتین با کلیدهای دیگر قاطی می‌شوند،
 *   • در ایمیل و copy/paste به‌هم می‌ریزند.
 * هر خطا یعنی یک تلاش ناموفق دیگر روی توکن، یعنی نزدیک‌شدن به سقف تلاش.
 * پس رمز موقت عمداً به «حروف انگلیسی + اعداد» محدود شده است.
 *
 * چرا حذف نویسه‌های مبهم؟ ادامهٔ همان منطق بالا:
 *   `O/0/o` و `I/l/1/i` در فونت ایمیل تقریباً یکسان دیده می‌شوند؛ کاربر نمی‌تواند
 *   مطمئن باشد کدام را دارد ⇒ تلاش مجدد.
 *
 * آنتروپی (بدون افت نسبت به نسخهٔ قبلی):
 *   • این نسخه: ۵۵ نماد × ۱۲ کاراکتر ⇒ 12 × log2(55) ≈ **۶۹٫۴ بیت**
 *   • نسخهٔ قبل: ۵۴ نماد × ۱۰ کاراکتر + ۲ نویسهٔ سمبول از ۸ گزینه
 *     ⇒ 10 × log2(54) + 2 × log2(8) ≈ ۶۳٫۶ بیت
 *   پس نه‌تنها کوتاه‌تر نشده، بلکه از نسخهٔ قبلی هم قوی‌تر است.
 *
 * حرکت یکنواخت: `randomInt` از `crypto` (نه `Math.random`).
 */

/**
 * الفبای الفبا-عددیِ «خوانا» — ۵۵ نماد.
 * حذف‌شده‌ها: `0 1 I O i l o` (همهٔ جفت‌های مبهم و هم‌خانواده‌های حروف کوچکشان).
 *   حروف بزرگ: ۲۴  ·  حروف کوچک: ۲۳  ·  ارقام: ۸  =  ۵۵
 */
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789"

/** طول رمز موقت — با حذف نویسه‌های سمبول، طول حفظ شده تا آنتروپی نریزد. */
export const TEMPORARY_PASSWORD_LENGTH = 12

/**
 * generateTemporaryPassword — یک رمز موقت تصادفیِ امن برمی‌گرداند.
 *
 * الگوریتم: یکنواخت و بدون بایز — در هر یک از ۱۲ جایگاه، یک نماد با
 * `crypto.randomInt(ALPHABET.length)` انتخاب می‌شود.
 *
 * Pure و بدون I/O — قابل تست مستقیم.
 */
export function generateTemporaryPassword(): string {
    const chars: string[] = []
    for (let i = 0; i < TEMPORARY_PASSWORD_LENGTH; i++) {
        chars.push(ALPHABET[randomInt(ALPHABET.length)])
    }
    return chars.join("")
}

/**
 * آیا رشته دقیقاً شکل یک رمز موقت معتبر دارد؟
 * (guard سمت ورودی/تست — **نه** جایگزین هش؛ اعتبارسنجی واقعی همیشه `bcrypt.compare` است.)
 */
export function isTemporaryPasswordShape(value: string): boolean {
    return (
        value.length === TEMPORARY_PASSWORD_LENGTH &&
        [...value].every((char) => ALPHABET.includes(char))
    )
}
